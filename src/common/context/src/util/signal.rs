use tokio::signal;

/// Process termination signal shared by application hosts and lifecycle hooks.
pub struct ShutdownSignal;

impl ShutdownSignal {
    pub async fn wait() {
        let ctrl_c = async {
            signal::ctrl_c().await.expect("failed to install Ctrl+C handler");
        };

        #[cfg(unix)]
        let terminate = async {
            signal::unix::signal(signal::unix::SignalKind::terminate())
                .expect("failed to install termination signal handler")
                .recv()
                .await;
        };

        #[cfg(not(unix))]
        let terminate = std::future::pending::<()>();

        tokio::select! {
            _ = ctrl_c => tracing::info!("graceful shutdown requested by Ctrl+C"),
            _ = terminate => tracing::info!("graceful shutdown requested by termination signal"),
        }
    }
}
