CREATE TABLE IF NOT EXISTS s_workflow (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    env TEXT NOT NULL DEFAULT 'legacy', tenant_id BIGINT, space_id BIGINT,
    name TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'STOPPED',
    flow_json JSONB NOT NULL DEFAULT '{"nodes":[],"connections":[]}',
    properties JSONB, secrets JSONB, description TEXT,
    created_by TEXT, updated_by TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), del_flag SMALLINT NOT NULL DEFAULT 0,
    CHECK ((tenant_id IS NULL AND space_id IS NULL AND env = 'legacy') OR
           (tenant_id IS NOT NULL AND space_id IS NOT NULL)),
    UNIQUE (env, tenant_id, space_id, id)
);
CREATE TABLE IF NOT EXISTS workflow_legacy_id (
    legacy_id UUID PRIMARY KEY, workflow_id BIGINT UNIQUE NOT NULL REFERENCES s_workflow(id)
);
DO $$
DECLARE legacy RECORD; mapped_id BIGINT;
BEGIN
    IF to_regclass('t_workflow') IS NOT NULL THEN
        FOR legacy IN SELECT * FROM t_workflow ORDER BY created_at, id LOOP
            IF NOT EXISTS (SELECT 1 FROM workflow_legacy_id WHERE legacy_id = legacy.id) THEN
                INSERT INTO s_workflow (name,flow_json,created_at,updated_at,del_flag)
                    VALUES (legacy.name,legacy.flow_json,legacy.created_at,legacy.updated_at,
                            CASE WHEN legacy.del_flag THEN 1 ELSE 0 END) RETURNING id INTO mapped_id;
                INSERT INTO workflow_legacy_id VALUES (legacy.id,mapped_id);
            END IF;
        END LOOP;
    END IF;
END $$;
CREATE TABLE IF NOT EXISTS workflow_run (
    run_id TEXT PRIMARY KEY, workflow_id BIGINT NOT NULL REFERENCES s_workflow(id),
    env TEXT NOT NULL, tenant_id BIGINT, space_id BIGINT,
    attempt_no INTEGER NOT NULL DEFAULT 0 CHECK (attempt_no >= 0),
    state TEXT NOT NULL CHECK (state IN ('queued','running','success','failed','stopped')),
    params JSONB NOT NULL DEFAULT '{}', started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    ended_at TIMESTAMPTZ, replay_of TEXT REFERENCES workflow_run(run_id),
    CHECK ((env = 'legacy' AND tenant_id IS NULL AND space_id IS NULL) OR
           (tenant_id IS NOT NULL AND space_id IS NOT NULL))
);
DO $$ BEGIN
    IF to_regclass('t_workflow_run') IS NOT NULL THEN
        INSERT INTO workflow_run(run_id,workflow_id,env,state,params,started_at,ended_at)
        SELECT r.id::text,m.workflow_id,'legacy',r.state,r.params,r.start_date,r.end_date
          FROM t_workflow_run r JOIN workflow_legacy_id m ON m.legacy_id=r.workflow_id
        ON CONFLICT (run_id) DO NOTHING;
    END IF;
END $$;
