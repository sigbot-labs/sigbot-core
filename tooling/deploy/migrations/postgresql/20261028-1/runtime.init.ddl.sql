CREATE OR REPLACE FUNCTION wallet_reject_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'immutable wallet facts: append a compensating journal'; END $$;
DROP TRIGGER IF EXISTS ledger_immutable ON s_ledger;
CREATE TRIGGER ledger_immutable BEFORE UPDATE OR DELETE ON s_ledger
    FOR EACH ROW EXECUTE FUNCTION wallet_reject_mutation();
DROP TRIGGER IF EXISTS journal_immutable ON wallet_journal;
CREATE TRIGGER journal_immutable BEFORE UPDATE OR DELETE ON wallet_journal
    FOR EACH ROW EXECUTE FUNCTION wallet_reject_mutation();
DROP TRIGGER IF EXISTS posting_immutable ON wallet_posting;
CREATE TRIGGER posting_immutable BEFORE UPDATE OR DELETE ON wallet_posting
    FOR EACH ROW EXECUTE FUNCTION wallet_reject_mutation();
CREATE OR REPLACE FUNCTION wallet_check_balanced() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM wallet_posting WHERE wallet_id=NEW.wallet_id
          AND producer_node_id=NEW.producer_node_id AND run_id=NEW.run_id AND seq=NEW.seq) OR EXISTS (
        SELECT asset FROM wallet_posting WHERE wallet_id=NEW.wallet_id
          AND producer_node_id=NEW.producer_node_id AND run_id=NEW.run_id AND seq=NEW.seq GROUP BY asset HAVING SUM(amount) <> 0
    ) THEN RAISE EXCEPTION 'wallet journal must balance per asset'; END IF;
    RETURN NULL;
END $$;
DROP TRIGGER IF EXISTS journal_balanced ON wallet_journal;
CREATE CONSTRAINT TRIGGER journal_balanced AFTER INSERT ON wallet_journal
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION wallet_check_balanced();
DROP TRIGGER IF EXISTS posting_balanced ON wallet_posting;
CREATE CONSTRAINT TRIGGER posting_balanced AFTER INSERT ON wallet_posting
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION wallet_check_balanced();
